<?php

declare(strict_types=1);

namespace core\apidoc;

/** 从实际发布的 OpenAPI 导出请求和响应类型；未知业务 data 保留 unknown。 */
final class TypeScriptGenerator
{
    /** @param array<string, mixed> $document */
    public function generate(array $document): string
    {
        $lines = ['// Generated by api:export. Do not edit.', 'export interface ApiSchemas {'];
        foreach ($document['components']['schemas'] ?? [] as $name => $schema) {
            $lines[] = '  ' . $this->quote($name) . ': ' . $this->schema($schema) . ';';
        }
        $lines[] = '}';
        $lines[] = 'export interface ApiOperations {';
        foreach ($document['paths'] ?? [] as $path => $methods) {
            foreach ($methods as $method => $operation) {
                if (!in_array(strtolower($method), ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'], true)) {
                    continue;
                }
                $parameters = ['path' => [], 'query' => []];
                foreach ($operation['parameters'] ?? [] as $parameter) {
                    $location = $parameter['in'] ?? '';
                    if (array_key_exists($location, $parameters)) {
                        $parameters[$location][] = $this->quote($parameter['name'])
                            . (($parameter['required'] ?? false) ? '' : '?') . ': '
                            . $this->schema($parameter['schema'] ?? []) . ';';
                    }
                }
                $body = $operation['requestBody']['content']['application/json']['schema'] ?? [];
                $response = $operation['responses'][200]['content']['application/json']['schema'] ?? [];
                $lines[] = '  ' . $this->quote(strtoupper($method) . ' ' . $path) . ': {';
                foreach ($parameters as $location => $fields) {
                    $lines[] = '    ' . $location . ': { ' . implode(' ', $fields) . ' };';
                }
                $lines[] = '    body: ' . $this->schema($body) . ';';
                $success = [];
                foreach ($response['oneOf'] ?? [] as $candidate) {
                    if (($candidate['properties']['code']['enum'] ?? null) === [200]) {
                        $success = $candidate;
                        break;
                    }
                }
                $lines[] = '    success: ' . $this->schema($success) . ';';
                $lines[] = '    response: ' . $this->schema($response) . ';';
                $lines[] = '  };';
            }
        }
        $lines[] = '}';

        return implode("\n", $lines) . "\n";
    }

    /** @param array<string, mixed> $schema */
    private function schema(array $schema): string
    {
        $type = $this->nonNullableSchema($schema);

        return ($schema['nullable'] ?? false) ? '(' . $type . ' | null)' : $type;
    }

    /** @param array<string, mixed> $schema */
    private function nonNullableSchema(array $schema): string
    {
        if (isset($schema['$ref'])) {
            $prefix = '#/components/schemas/';
            if (!str_starts_with($schema['$ref'], $prefix)) {
                return 'unknown';
            }

            return 'ApiSchemas[' . $this->quote(str_replace(['~1', '~0'], ['/', '~'], substr($schema['$ref'], strlen($prefix)))) . ']';
        }
        foreach (['oneOf', 'anyOf', 'allOf'] as $composition) {
            if (isset($schema[$composition])) {
                $types = array_map(fn (array $part): string => $this->schema($part), $schema[$composition]);

                return '(' . implode($composition === 'allOf' ? ' & ' : ' | ', $types) . ')';
            }
        }
        if (isset($schema['enum']) && $schema['enum'] !== []) {
            return implode(' | ', array_map(fn (mixed $value): string => $this->quote($value), $schema['enum']));
        }
        return match ($schema['type'] ?? null) {
            'integer', 'number' => 'number',
            'string' => 'string',
            'boolean' => 'boolean',
            'array' => 'Array<' . $this->schema($schema['items'] ?? []) . '>',
            'object' => $this->object($schema),
            default => 'unknown',
        };
    }

    /** @param array<string, mixed> $schema */
    private function object(array $schema): string
    {
        $fields = [];
        foreach ($schema['properties'] ?? [] as $name => $property) {
            $fields[] = $this->quote($name) . (in_array($name, $schema['required'] ?? [], true) ? '' : '?')
                . ': ' . $this->schema($property) . ';';
        }
        $additional = $schema['additionalProperties'] ?? true;
        if ($additional !== false) {
            // 未声明 additionalProperties 的 OpenAPI 对象允许额外字段。
            $fields[] = '[key: string]: ' . (is_array($additional) ? $this->schema($additional) : 'unknown') . ';';
        }

        return '{ ' . implode(' ', $fields) . ' }';
    }

    private function quote(mixed $value): string
    {
        return json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
    }
}
